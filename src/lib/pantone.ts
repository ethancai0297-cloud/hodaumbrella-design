export function normalizePantone(input: string): string {
  return input
    .toLowerCase()
    .replace(/pantone|pms/g, "")
    .replace(/\s+/g, "")
    .replace(/[-_]/g, "")
    .replace(/(c|u|cp|up|m)$/g, "")
    .trim();
}

export function pantoneToHex(input: string): string | null {
  if (!input) return null;
  const key = normalizePantone(input);
  if (!key) return null;
  return PANTONE_MAP[key] || PANTONE_MAP[key.replace(/^0+/, "")] || null;
}
